"""Analyze normalized local project inputs and write results to a separate directory."""

import argparse
import hashlib
import json
import platform
from importlib.metadata import version
from pathlib import Path
import pandas as pd

from .data import load_data, join_outcomes
from .metrics import launch_metrics
from .models import fit_segment_model
from .plots import save_figures


def run(data_dir, output_dir, label, min_rows=30, min_stores=5):
    data_dir, output_dir = Path(data_dir).resolve(), Path(output_dir).resolve()
    project = Path(__file__).resolve().parents[2]
    if output_dir == project or project in output_dir.parents:
        raise ValueError("Write client results outside the public repository")
    frames = load_data(data_dir)
    metrics = launch_metrics(frames)
    outcomes = join_outcomes(frames)
    tables = output_dir / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    for name, frame in metrics.items():
        frame.to_csv(tables / f"{name}.csv", index=False, float_format="%.8g")
    diagnostics = {}
    for moderator in ["brand", "division"]:
        support, contrasts, diag = fit_segment_model(outcomes, moderator, min_rows, min_stores)
        support.to_csv(tables / f"{moderator}_support.csv", index=False, float_format="%.8g")
        contrasts.to_csv(tables / f"{moderator}_contrasts.csv", index=False, float_format="%.8g")
        diagnostics[moderator] = diag
        if moderator == "division":
            save_figures(metrics, support, contrasts, output_dir / "figures", label)
    manifest = {"data_label": label,
                "environment": {"python": platform.python_version(),
                                **{name: version(name) for name in ["pandas", "numpy", "statsmodels", "matplotlib"]}},
                "input_sha256": {f"{name}.csv": hashlib.sha256((data_dir/f"{name}.csv").read_bytes()).hexdigest()
                                 for name in sorted(frames)},
                "input_rows": {name: len(frame) for name, frame in frames.items()},
                "window": "L+1 through L+3: three full months following launch",
                "complete_items": int(metrics["item_coverage_3m"].complete_3m.sum()),
                "incomplete_items": int((~metrics["item_coverage_3m"].complete_3m).sum()),
                "models": diagnostics}
    (output_dir / "run_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    summary = metrics["program_3m"]
    lines = [f"# Analysis output: {label}", "", "Generated by `awg-analyze`.", "",
             "## Launch window", "", "The primary window is L+1 through L+3, using calendar periods across year boundaries. Totals use complete-follow-up items; coverage status tracks the remaining cohorts for review.",
             "", f"Complete-follow-up items: {manifest['complete_items']}. Items tracked for follow-up review: {manifest['incomplete_items']}.", "",
             "## Participation comparison", "", "| Program | Roster stores | Mean 3M net sales ($) |",
             "|---|---:|---:|"]
    lines += [f"| {r.program} | {r.n_stores} | {r.mean_sales_3m:.2f} |" for r in summary.itertuples()]
    lines += ["", "## Model interpretation", "",
              "Separate brand and division interaction models estimate within-segment program-vs-None associations. Store-clustered intervals and BH-adjusted p-values accompany each supported comparison.",
              "", "This report uses the supplied local project inputs. The companion import audit records calendar definitions, product mappings, and working assumptions.",
              "", "The model target is source-indexed cumulative m12 sales. Launch-calendar reconciliation and matched follow-up windows are next-stage analytical tasks.",
              "", "See `run_manifest.json`, `tables/`, and `figures/` for reproducible evidence."]
    (output_dir / "analysis_summary.md").write_text("\n".join(lines) + "\n")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True, help="Directory containing normalized local project inputs")
    parser.add_argument("--output", type=Path, required=True, help="Result directory outside the public repository")
    parser.add_argument("--label", default="LOCAL PROJECT ANALYSIS")
    parser.add_argument("--min-rows", type=int, default=30)
    parser.add_argument("--min-stores", type=int, default=5)
    args = parser.parse_args()
    if args.min_rows < 2 or args.min_stores < 2:
        parser.error("Support thresholds must each be at least 2")
    manifest = run(args.data, args.output, args.label, args.min_rows, args.min_stores)
    print(f"Completed {manifest['data_label']}: {manifest['input_rows']}")


if __name__ == "__main__":
    main()
